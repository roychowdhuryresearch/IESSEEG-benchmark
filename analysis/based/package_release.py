#!/usr/bin/env python
"""Build the public BASED annotation release.

Produces one long-format CSV with all 140 independent (rater, recording)
BASED ratings -- per-rater, both treatment conditions, window offsets kept
where the rating could be aligned to a recording position -- plus a README
documenting schema, provenance, and caveats.

Rater identities are pseudonymous role-coded IDs (EXPERT1-4, TRAINEE1-3);
no other rater information is released.

Inputs (env):
  IESSEEG_BASED_XLSX     the IRR export workbook (MASTER sheet)
  IESSEEG_BASED_PAIRS    epoch_pairs.csv (aligned 115 with offset_sec)
  IESSEEG_BENCH_SPLITS   released splits/ (condition + patient linkage)
  IESSEEG_RELEASE_OUT    output directory (e.g. analysis/based/release)
"""

import glob
import os

import numpy as np
import pandas as pd


def env(name):
    v = os.environ.get(name)
    if not v:
        raise SystemExit(f"Set {name}")
    return v


README = """# BASED score annotations for IESSEEG

One row per independent rating: seven raters (four board-certified
pediatric epileptologists, EXPERT1-4; three trainees, TRAINEE1-3) each
independently searched one full overnight recording for a 5-minute window
they judged representative and scored that window on the BASED scale
(Mytinger et al., 2015; 2021). 20 recordings x 7 raters = 140 ratings.

## Columns

| column               | meaning                                                        |
|----------------------|----------------------------------------------------------------|
| long_recording_id    | overnight study identifier                                     |
| treatment_condition  | PRE (before first-line therapy) or POST (follow-up study)      |
| patient_id           | benchmark patient id; only PRE recordings belong to the        |
|                      | benchmark corpus, POST rows have no linkage and show NA        |
| rater                | pseudonymous rater code (EXPERT1-4, TRAINEE1-3)                |
| rater_role           | Expert / Trainee                                               |
| based_score          | BASED score assigned to the rater's chosen 5-minute window     |
| window_offset_sec    | start of that window, seconds from recording onset; NA for the |
|                      | 25 ratings whose review-system timestamp falls outside the EDF |
|                      | span (clock skew) and could not be aligned                     |

## Caveats

- The 10 POST recordings extend beyond the pre-treatment corpus that
  constitutes the benchmark; they are supplementary annotation, released
  because the pre/post contrast carries the strongest validation signal.
- Raters chose *different* windows (median pairwise gap in recording
  position 3.5 h among aligned ratings); the 140 ratings are independently
  selected (window, score) pairs, not repeated readings of one stimulus.
- window_offset_sec is meaningful relative to the source overnight
  recordings, which are longer than the released 30-minute clips.
- Scores are annotations of fully de-identified recordings; rater codes
  are pseudonyms.

Generated by analysis/based/package_release.py from the annotation
workbook; regenerate rather than hand-editing.
"""


def main():
    out_dir = env("IESSEEG_RELEASE_OUT")
    os.makedirs(out_dir, exist_ok=True)

    m = pd.ExcelFile(env("IESSEEG_BASED_XLSX")).parse("MASTER")
    score_cols = [c for c in m.columns if c.startswith("02_B_")]
    long = m.melt(id_vars=["Code"], value_vars=score_cols,
                  var_name="rater", value_name="based_score")
    long["rater"] = long.rater.str.replace("02_B_", "", regex=False)
    long["rater_role"] = np.where(long.rater.str.startswith("EXPERT"),
                                  "Expert", "Trainee")
    long = long.rename(columns={"Code": "long_recording_id"})

    # condition + patient linkage from the released benchmark splits
    frames = []
    for f in glob.glob(os.path.join(env("IESSEEG_BENCH_SPLITS"), "**", "*.csv"),
                       recursive=True):
        try:
            frames.append(pd.read_csv(
                f, usecols=["long_recording_id", "patient_id"]))
        except Exception:
            continue
    link = pd.concat(frames).drop_duplicates("long_recording_id")
    long = long.merge(link, on="long_recording_id", how="left")
    long["treatment_condition"] = np.where(long.patient_id.notna(), "PRE", "POST")

    pairs = pd.read_csv(env("IESSEEG_BASED_PAIRS"))[
        ["recording_id", "rater", "offset_sec"]].rename(
        columns={"recording_id": "long_recording_id",
                 "offset_sec": "window_offset_sec"})
    long = long.merge(pairs, on=["long_recording_id", "rater"], how="left")

    long = long[["long_recording_id", "treatment_condition", "patient_id",
                 "rater", "rater_role", "based_score", "window_offset_sec"]]
    long = long.sort_values(
        ["treatment_condition", "long_recording_id", "rater"],
        ascending=[False, True, True])

    assert len(long) == 140, len(long)
    assert long.window_offset_sec.notna().sum() == 115
    assert (long.treatment_condition == "PRE").sum() == 70
    assert long[long.treatment_condition == "PRE"].patient_id.notna().all()

    csv_path = os.path.join(out_dir, "based_annotations.csv")
    long.to_csv(csv_path, index=False, float_format="%.6g")
    with open(os.path.join(out_dir, "README.md"), "w") as fh:
        fh.write(README)
    print(f"wrote {csv_path}  ({len(long)} rows, "
          f"{long.long_recording_id.nunique()} recordings, "
          f"{long.rater.nunique()} raters)")
    print(long.groupby('treatment_condition').based_score.describe().round(2))


if __name__ == "__main__":
    main()
